-- OWNER APP UPDATE 4: customer udhaar payments, customer and supplier photos, product videos
-- Run this ONCE in Supabase > SQL Editor, AFTER owner_update_2_migration.sql and
-- owner_update_3_supplier_bill_file.sql.
-- It only ADDS columns, a table, storage buckets, policies and functions.
-- It drops and deletes nothing. Existing products, stock, bills, customers, suppliers and payments are untouched.
-- Tasks / reminders are kept on the phone only and need no server table.
-- The last result line says "OK: update 4 is installed ...".
-- =====================================================================

-- STEP 1: new columns on existing tables (nullable / defaulted)
alter table public.products       add column if not exists videos    jsonb default '[]'::jsonb;
alter table public.owner_customers add column if not exists photo_url text;
alter table public.owner_suppliers add column if not exists photo_url text;

-- STEP 2: customer payments (udhaar received). bill_id empty = payment on account
create table if not exists public.owner_customer_payments (
  id          text primary key,            -- generated by the app, so a retry can never be saved twice
  mobile      text not null,
  bill_id     text,
  amount      numeric not null,
  method      text,
  note        text,
  paid_at     timestamptz default now(),
  created_at  timestamptz default now()
);
alter table public.owner_customer_payments enable row level security;

-- STEP 3: storage buckets (public read, owner app upload). Videos up to 25 MB, photos up to 5 MB
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('profile-photos', 'profile-photos', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do nothing;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('product-videos', 'product-videos', true, 26214400, array['video/mp4','video/quicktime','video/webm'])
on conflict (id) do nothing;

drop policy if exists "owner app upload profile photos" on storage.objects;
create policy "owner app upload profile photos" on storage.objects
  for insert to anon, authenticated with check (bucket_id = 'profile-photos');
drop policy if exists "public read profile photos" on storage.objects;
create policy "public read profile photos" on storage.objects
  for select to anon, authenticated using (bucket_id = 'profile-photos');

drop policy if exists "owner app upload product videos" on storage.objects;
create policy "owner app upload product videos" on storage.objects
  for insert to anon, authenticated with check (bucket_id = 'product-videos');
drop policy if exists "public read product videos" on storage.objects;
create policy "public read product videos" on storage.objects
  for select to anon, authenticated using (bucket_id = 'product-videos');

-- STEP 4: functions
-- Saves the full list of product videos (URLs). Empty list removes them. Stock and images are not touched.
create or replace function public.owner_set_product_videos(p_code text, p_id text, p_videos jsonb) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform _owner_ok(p_code);
  update products set videos = coalesce(p_videos, '[]'::jsonb) where id = p_id;
  if not found then raise exception 'PRODUCT_NOT_FOUND'; end if;
end $$;

-- Customer photo: an empty URL removes the photo. The customer's other details are not changed.
create or replace function public.owner_set_customer_photo(p_code text, p_mobile text, p_url text) returns void
language plpgsql security definer set search_path = public as $$
declare m text := regexp_replace(coalesce(p_mobile,''), '\D', '', 'g');
begin
  perform _owner_ok(p_code);
  if length(m) > 10 then m := right(m, 10); end if;
  update owner_customers set photo_url = nullif(p_url, ''), updated_at = now() where mobile = m;
  if not found then raise exception 'CUSTOMER_NOT_FOUND'; end if;
end $$;

-- Supplier photo: an empty URL removes the photo.
create or replace function public.owner_set_supplier_photo(p_code text, p_id text, p_url text) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform _owner_ok(p_code);
  update owner_suppliers set photo_url = nullif(p_url, ''), updated_at = now() where id = p_id;
  if not found then raise exception 'SUPPLIER_NOT_FOUND'; end if;
end $$;

-- Customer payment. Idempotent by id.
create or replace function public.owner_add_customer_payment(p_code text, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare m text := regexp_replace(coalesce(p->>'mobile',''), '\D', '', 'g');
begin
  perform _owner_ok(p_code);
  if length(m) > 10 then m := right(m, 10); end if;
  if coalesce(trim(p->>'id'),'') = '' or length(m) <> 10 or coalesce((p->>'amount')::numeric, 0) <= 0 then
    raise exception 'INVALID_PAYMENT';
  end if;
  insert into owner_customer_payments (id, mobile, bill_id, amount, method, note, paid_at, created_at)
  values (p->>'id', m, nullif(p->>'bill_id',''), (p->>'amount')::numeric,
          nullif(p->>'method',''), nullif(p->>'note',''), coalesce((p->>'paid_at')::timestamptz, now()), now())
  on conflict (id) do nothing;
  if not found then
    return jsonb_build_object('ok', true, 'duplicate', true);
  end if;
  return jsonb_build_object('ok', true);
end $$;

create or replace function public.owner_list_customer_payments(p_code text) returns setof public.owner_customer_payments
language plpgsql security definer set search_path = public as $$
begin perform _owner_ok(p_code); return query select * from owner_customer_payments order by paid_at desc limit 20000; end $$;

revoke all on function public.owner_set_product_videos(text,text,jsonb) from public;
revoke all on function public.owner_set_customer_photo(text,text,text)  from public;
revoke all on function public.owner_set_supplier_photo(text,text,text)  from public;
revoke all on function public.owner_add_customer_payment(text,jsonb)    from public;
revoke all on function public.owner_list_customer_payments(text)        from public;
grant execute on function public.owner_set_product_videos(text,text,jsonb) to anon, authenticated;
grant execute on function public.owner_set_customer_photo(text,text,text)  to anon, authenticated;
grant execute on function public.owner_set_supplier_photo(text,text,text)  to anon, authenticated;
grant execute on function public.owner_add_customer_payment(text,jsonb)    to anon, authenticated;
grant execute on function public.owner_list_customer_payments(text)        to anon, authenticated;

-- STEP 5: check (the last line says whether everything is in place)
select case
         when exists (select 1 from information_schema.columns
                       where table_schema = 'public' and table_name = 'products' and column_name = 'videos')
          and to_regclass('public.owner_customer_payments') is not null
          and exists (select 1 from storage.buckets where id = 'product-videos')
          and exists (select 1 from storage.buckets where id = 'profile-photos')
         then 'OK: update 4 is installed (customer payments, photos, product videos).'
         else 'PROBLEM: update 4 is incomplete - send a screenshot of the error above.'
       end as status;
