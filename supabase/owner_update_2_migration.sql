-- STEP 3: POS bill - same stock logic as before, plus the new details ---------------------------
-- The stock loop is unchanged (one atomic, idempotent change per line: "<billId>#<line>").
-- The duplicate check is now a single atomic insert, so even two simultaneous retries deduct only once.
create or replace function public.owner_create_bill(p_code text, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare rec record; warns jsonb := '[]'::jsonb; bid text := p->>'id';
begin
  perform _owner_ok(p_code);
  insert into pos_bills (id, bill_no, total, payment_method, items, created_at,
                         sales_person_id, sales_person, customer_name, customer_mobile, customer_address,
                         total_mrp, total_discount, sub_total, tax_percent, tax_amount, amount_paid, balance, meta)
  values (bid, p->>'bill_no', (p->>'total')::numeric, p->>'payment_method', p->'items',
          coalesce((p->>'created_at')::timestamptz, now()),
          nullif(p->>'sales_person_id',''), nullif(p->>'sales_person',''),
          nullif(p->>'customer_name',''), nullif(p->>'customer_mobile',''), nullif(p->>'customer_address',''),
          (p->>'total_mrp')::numeric, (p->>'total_discount')::numeric, (p->>'sub_total')::numeric,
          (p->>'tax_percent')::numeric, (p->>'tax_amount')::numeric,
          (p->>'amount_paid')::numeric, (p->>'balance')::numeric, p->'meta')
  on conflict (id) do nothing;
  if not found then
    return jsonb_build_object('ok', true, 'duplicate', true);
  end if;
  for rec in select value as it, ordinality as idx
               from jsonb_array_elements(coalesce(p->'items','[]'::jsonb)) with ordinality loop
    begin
      perform _apply_delta(rec.it->>'productId', rec.it->>'colour', rec.it->>'size',
                           -((rec.it->>'qty')::int), bid || '#' || rec.idx, 'POS_SALE', p->>'bill_no');
    exception when others then
      warns := warns || jsonb_build_array(sqlerrm);
    end;
  end loop;
  return jsonb_build_object('ok', true, 'warnings', warns);
end $$;

-- STEP 4: staff ---------------------------------------------------------------------------------
create or replace function public.owner_upsert_staff(p_code text, p jsonb) returns text
language plpgsql security definer set search_path = public as $$
begin
  perform _owner_ok(p_code);
  if coalesce(trim(p->>'id'),'') = '' or coalesce(trim(p->>'name'),'') = '' then
    raise exception 'INVALID_STAFF';
  end if;
  insert into owner_staff (id, name, mobile, active, created_at, updated_at)
  values (p->>'id', trim(p->>'name'), nullif(trim(coalesce(p->>'mobile','')),''),
          coalesce((p->>'active')::boolean, true), coalesce((p->>'created_at')::timestamptz, now()), now())
  on conflict (id) do update
     set name = excluded.name, mobile = excluded.mobile, active = excluded.active, updated_at = now();
  return p->>'id';
end $$;

create or replace function public.owner_list_staff(p_code text) returns setof public.owner_staff
language plpgsql security definer set search_path = public as $$
begin perform _owner_ok(p_code); return query select * from owner_staff order by name; end $$;

-- STEP 5: customers (walk-in / shop customers, key = mobile) -------------------------------------
-- A bill that only knows the mobile never blanks a name or address that is already saved;
-- an explicit edit in the Customers screen ("force") replaces the values.
create or replace function public.owner_upsert_customer(p_code text, p jsonb) returns text
language plpgsql security definer set search_path = public as $$
declare m text := regexp_replace(coalesce(p->>'mobile',''), '\D', '', 'g');
begin
  perform _owner_ok(p_code);
  if length(m) > 10 then m := right(m, 10); end if;
  if length(m) <> 10 then raise exception 'INVALID_MOBILE'; end if;
  insert into owner_customers (mobile, name, address, created_at, updated_at)
  values (m, nullif(trim(coalesce(p->>'name','')),''), nullif(trim(coalesce(p->>'address','')),''),
          coalesce((p->>'created_at')::timestamptz, now()), now())
  on conflict (mobile) do update set
     name    = case when coalesce((p->>'force')::boolean, false) then excluded.name
                    else coalesce(excluded.name, owner_customers.name) end,
     address = case when coalesce((p->>'force')::boolean, false) then excluded.address
                    else coalesce(excluded.address, owner_customers.address) end,
     updated_at = now();
  return m;
end $$;

create or replace function public.owner_list_pos_customers(p_code text) returns setof public.owner_customers
language plpgsql security definer set search_path = public as $$
begin perform _owner_ok(p_code); return query select * from owner_customers order by name limit 20000; end $$;

