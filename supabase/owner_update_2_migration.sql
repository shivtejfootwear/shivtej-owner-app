-- p = { id, supplier_id, bill_no, bill_date, amount, note, add_stock,
--       items:[{productId,colour,size,qty,cost,article,name}] }
-- Idempotent by id. Each stock line is applied once with the fixed op id "PUR:<id>:<line>".
create or replace function public.owner_create_purchase(p_code text, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare rec record; warns jsonb := '[]'::jsonb; pid text := p->>'id'; addst boolean;
begin
  perform _owner_ok(p_code);
  if coalesce(trim(pid),'') = '' or coalesce(trim(p->>'supplier_id'),'') = '' then
    raise exception 'INVALID_PURCHASE';
  end if;
  addst := coalesce((p->>'add_stock')::boolean, true);
  insert into owner_purchase_bills (id, supplier_id, bill_no, bill_date, amount, items, add_stock, note, created_at)
  values (pid, p->>'supplier_id', p->>'bill_no', coalesce((p->>'bill_date')::timestamptz, now()),
          coalesce((p->>'amount')::numeric, 0), coalesce(p->'items','[]'::jsonb), addst,
          nullif(p->>'note',''), now())
  on conflict (id) do nothing;
  if not found then
    return jsonb_build_object('ok', true, 'duplicate', true);
  end if;
  if addst then
    for rec in select value as it, ordinality as idx
                 from jsonb_array_elements(coalesce(p->'items','[]'::jsonb)) with ordinality loop
      begin
        perform _apply_delta(rec.it->>'productId', rec.it->>'colour', rec.it->>'size',
                             greatest((rec.it->>'qty')::int, 0), 'PUR:' || pid || ':' || rec.idx,
                             'PURCHASE', coalesce(p->>'bill_no', pid));
      exception when others then
        warns := warns || jsonb_build_array(sqlerrm);
      end;
    end loop;
  end if;
  return jsonb_build_object('ok', true, 'warnings', warns);
end $$;

create or replace function public.owner_list_purchases(p_code text) returns setof public.owner_purchase_bills
language plpgsql security definer set search_path = public as $$
begin perform _owner_ok(p_code); return query select * from owner_purchase_bills order by bill_date desc limit 5000; end $$;

create or replace function public.owner_add_supplier_payment(p_code text, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
begin
  perform _owner_ok(p_code);
  if coalesce(trim(p->>'id'),'') = '' or coalesce(trim(p->>'supplier_id'),'') = '' or coalesce((p->>'amount')::numeric, 0) <= 0 then
    raise exception 'INVALID_PAYMENT';
  end if;
  insert into owner_supplier_payments (id, supplier_id, bill_id, amount, method, note, paid_at, created_at)
  values (p->>'id', p->>'supplier_id', nullif(p->>'bill_id',''), (p->>'amount')::numeric,
          nullif(p->>'method',''), nullif(p->>'note',''), coalesce((p->>'paid_at')::timestamptz, now()), now())
  on conflict (id) do nothing;
  if not found then
    return jsonb_build_object('ok', true, 'duplicate', true);
  end if;
  return jsonb_build_object('ok', true);
end $$;

create or replace function public.owner_list_supplier_payments(p_code text) returns setof public.owner_supplier_payments
language plpgsql security definer set search_path = public as $$
begin perform _owner_ok(p_code); return query select * from owner_supplier_payments order by paid_at desc limit 20000; end $$;

