-- Adds: sales person + customer + discount/tax/payment details on POS bills, staff,
--       owner-app customers, suppliers, purchase bills (with stock), supplier payments.
--
-- SAFE BY DESIGN
--   * Nothing is dropped, truncated, recreated or overwritten. No existing row is changed.
--   * Only NEW tables, NEW nullable columns on pos_bills (the table created by owner_app_setup.sql)
--     and "create or replace" of owner_create_bill (same name + same arguments, old calls still work).
--   * Your website tables (products, orders, customers, payments ...) are not touched at all.
--   * It can be run again at any time; it does nothing the second time.
-- ORDER: owner_app_setup.sql first, website_sync.sql second, THIS FILE third.
-- =====================================================================

